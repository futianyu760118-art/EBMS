test('边界：自动产生的待办暴露触发依据，触发依据缺失时显式报警而非静默', () => {
  const model = buildTodoModel(OVERVIEW);
  const auto = model.rows.filter((r) => r.autoGenerated);

  for (const row of auto) {
    assert.ok(row.triggerBasis, '自动产生的待办必须带触发依据');
    assert.ok(row.triggerRule.includes('R-'), '触发依据含规则编码');
    assert.ok(row.triggerSummary, '触发依据含可读摘要');
    assert.ok(row.triggerAnchor, '触发依据锚定到结果指标或原因项');
    assert.equal(row.triggerMissing, false);
  }
  // 人工派发不写触发依据，且不算缺失
  assert.equal(buildTodoRow(ITEMS[1]).triggerBasis, null);
  assert.equal(buildTodoRow(ITEMS[1]).triggerMissing, false);

  assert.ok(model.triggerNotice.includes('2 条待办均含触发依据'));
  assert.equal(model.triggerMissingCount, 0);

  // 触发依据缺失（异常数据）时不静默：计数上升 + 文案改为告警
  const broken = buildTodoModel({
    ...OVERVIEW,
    items: [ITEMS[0], { ...ITEMS[3], triggerBasis: null }],
  });
  assert.equal(broken.triggerMissingCount, 1);
  assert.ok(broken.triggerNotice.includes('1 条自动产生的待办缺少触发依据'));
  assert.equal(buildTodoRow({ ...ITEMS[3], triggerBasis: null }).triggerMissing, true);

  assert.equal(triggerAnchorText({ resultMetricCode: 'order_delivery' }), '结果指标 order_delivery');
  assert.equal(triggerAnchorText({ reasonId: 'r-1' }), '原因项');
  assert.equal(triggerAnchorText(null), null);
});

