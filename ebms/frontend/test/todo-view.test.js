test('场景 2：两种来源并存，且来源与「自动/人工」标记一一对应', () => {
  const model = buildTodoModel(OVERVIEW);

  assert.equal(model.bothSourcesPresent, true);
  assert.ok(model.sourceNotice.includes('规则自动产生 2 条'));
  assert.ok(model.sourceNotice.includes('人工派发 3 条'));
  assert.ok(model.sourceNotice.includes('并存成立'));

  const auto = model.rows.filter((r) => r.autoGenerated);
  const manual = model.rows.filter((r) => !r.autoGenerated);
  assert.deepEqual(auto.map((r) => r.source), ['rule', 'rule']);
  assert.ok(manual.every((r) => r.source === 'manual'));

  // 只有一种来源时，并存判定为假且文案如实说明
  const single = buildTodoModel({
    ...OVERVIEW,
    items: ITEMS.filter((i) => i.source === 'manual'),
    summary: { ...OVERVIEW.summary, ruleSourced: 0, bothSourcesPresent: false },
  });
  assert.equal(single.bothSourcesPresent, false);
  assert.ok(single.sourceNotice.includes('仅一种来源'));
});

test('场景 3：状态三类齐备，可流转动作按状态机下发并翻译成界面按钮文案', () => {
  const model = buildTodoModel(OVERVIEW);
  assert.deepEqual(model.statuses.map((s) => s.label), ['待处理', '处理中', '已完成']);

  const byStatus = Object.fromEntries(model.rows.map((r) => [r.status, r]));
  assert.equal(byStatus.pending.statusLabel, '待处理');
  assert.equal(byStatus.in_progress.statusLabel, '处理中');
  assert.equal(byStatus.done.statusLabel, '已完成');

  // 待处理 → 只有「开始处理」；处理中 → 「标记完成」与「退回待处理」；已完成 → 终态无动作
  assert.deepEqual(byStatus.pending.allowedTransitions.map((t) => t.actionLabel), ['开始处理']);
  assert.deepEqual(
    byStatus.in_progress.allowedTransitions.map((t) => t.actionLabel),
    ['退回待处理', '标记完成']
  );
  assert.deepEqual(byStatus.done.allowedTransitions, []);

  // 终态不再提供认领；未指派的未完成项才可认领
  assert.equal(byStatus.done.claimable, false);
  assert.equal(buildTodoRow(ITEMS[3]).claimable, true);
  assert.equal(buildTodoRow(ITEMS[0]).claimable, false);
});

test('场景 4：筛选条件转成查询串，空值不下发（避免被当成筛选值）', () => {
  assert.equal(todoQuery({}), '');
  assert.equal(todoQuery({ owner: '', status: '', overdue: null }), '');
  assert.equal(todoQuery({ status: 'pending' }), '?status=pending');
  assert.equal(todoQuery({ overdue: true }), '?overdue=true');
  assert.equal(todoQuery({ overdue: false }), '?overdue=false');
  // 责任人含空格与斜杠，必须转义后仍能原样还原（空格按 URLSearchParams 约定编码为 +）
  const query = todoQuery({ owner: '生产中心 / 赵计划' });
  assert.ok(query.startsWith('?owner='));
  assert.equal(new URLSearchParams(query.slice(1)).get('owner'), '生产中心 / 赵计划');
  const full = todoQuery({ owner: 'A', status: 'done', source: 'rule', dueBefore: '2026-10-01T00:00:00.000Z', overdue: true });
  const parsed = new URLSearchParams(full.slice(1));
  assert.deepEqual([...parsed.keys()], ['owner', 'status', 'source', 'due_before', 'overdue']);
  assert.equal(parsed.get('due_before'), '2026-10-01T00:00:00.000Z');
  assert.equal(parsed.get('overdue'), 'true');
});

