test('边界：截止时间按本地日历取日，不因 UTC 换算把日期显示偏移一天', () => {
  // 接口返回 UTC 时刻：业务时区（UTC+8）的零点在 UTC 上是前一天 16:00
  const businessMidnightUtc = '2026-09-19T16:00:00.000Z';
  assert.equal(dueText(businessMidnightUtc), localDate(businessMidnightUtc));
  assert.equal(dueText('2026-09-30T00:00:00+08:00'), localDate('2026-09-30T00:00:00+08:00'));

  // 回归防线：若实现退回「直接切 ISO 字符串」，在非 UTC 时区下就会与本地日历日不符
  if (new Date().getTimezoneOffset() !== 0) {
    assert.notEqual(dueText(businessMidnightUtc), '2026-09-19');
  }

  // 详情展示到时刻，避免「显示今天到期、却已判逾期」的观感矛盾
  assert.equal(dueDateTimeText(businessMidnightUtc), `${localDate(businessMidnightUtc)} ${localTime(businessMidnightUtc)}`);
  assert.ok(dueDateTimeText(businessMidnightUtc).startsWith(dueText(businessMidnightUtc)));

  assert.equal(dueText(null), NO_DUE_LABEL);
  assert.equal(dueText(''), NO_DUE_LABEL);
  assert.equal(dueText('not-a-date'), 'not-a-date', '非法值原样回显，不静默丢弃');
  assert.equal(dueDateTimeText(null), NO_DUE_LABEL);
});

test('场景 4：日期筛选值按本地「当天结束」解释，使「不晚于某日」包含该日全天', () => {
  const iso = endOfLocalDay('2026-10-01');
  const end = new Date(iso);
  assert.equal(end.getFullYear(), 2026);
  assert.equal(end.getMonth(), 9);
  assert.equal(end.getDate(), 1);
  assert.equal(end.getHours(), 23);
  assert.equal(end.getMinutes(), 59);
  // 非法值原样透传，由后端统一判错
  assert.equal(endOfLocalDay('2026-10'), '2026-10');
  assert.equal(endOfLocalDay(''), '');

  const query = todoQuery({ dueBefore: '2026-10-01' });
  assert.equal(new URLSearchParams(query.slice(1)).get('due_before'), iso);
});

