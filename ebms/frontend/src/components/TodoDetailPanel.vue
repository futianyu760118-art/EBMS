<script setup>
// F8（PAND-86）详情面板：七列字段 + 触发依据（边界）+ 流转留痕时间线（场景 3）。
// 纯展示组件：入参即 buildTodoDetailModel 的结果。
import { ref } from 'vue';
import { formatDateTimeLong } from '../format';

defineProps({
  model: { type: Object, required: true },
  busy: { type: Boolean, default: false },
  error: { type: String, default: '' },
});

const emit = defineEmits(['close', 'claim', 'transition', 'assign']);

const assignOwner = ref('');

function submitAssign(row) {
  const owner = assignOwner.value.trim();
  if (!owner) return;
  emit('assign', { row, owner });
}
</script>

<template>
  <aside class="detail-panel card" data-testid="todo-detail">
    <header class="detail-header">
      <div>
        <h3>{{ model.row?.title }}</h3>
        <p class="muted">
          {{ model.row?.code }}
          <span class="badge" :class="model.row?.autoGenerated ? 'badge-rule' : 'badge-manual'">
            {{ model.row?.sourceLabel }}
          </span>
        </p>
      </div>
      <button class="btn btn-ghost btn-sm" type="button" @click="emit('close')">关闭</button>
    </header>

    <p v-if="error" class="alert alert-error">{{ error }}</p>

    <dl class="detail-grid">
      <dt>关联结果 / 原因</dt>
      <dd data-testid="detail-relation">{{ model.row?.relationText }}</dd>
      <dt>责任人</dt>
      <dd data-testid="detail-owner">{{ model.row?.ownerLabel }}</dd>
      <dt>截止时间</dt>
      <dd data-testid="detail-due">
        <span class="strong">{{ model.row?.dueDateTimeText }}</span>
        <span v-if="model.row?.overdue" class="badge badge-danger" data-testid="detail-overdue">
          {{ model.row?.overdueLabel }}
        </span>
      </dd>
      <dt>状态</dt>
      <dd data-testid="detail-status">
        <span class="badge" :class="`badge-status-${model.row?.status}`">{{ model.row?.statusLabel }}</span>
      </dd>
    </dl>

    <section v-if="model.trigger" class="detail-section" data-testid="detail-trigger">
      <h4>触发依据</h4>
      <p class="muted">规则：{{ model.trigger.rule }}</p>
      <p>{{ model.trigger.summary }}</p>
      <p v-if="model.trigger.anchor" class="muted">锚定：{{ model.trigger.anchor }}</p>
      <p v-if="model.trigger.period" class="muted">期间：{{ model.trigger.period }}</p>
      <p v-if="model.trigger.detectedAt" class="muted">
        检出时间：{{ formatDateTimeLong(model.trigger.detectedAt) }}
      </p>
    </section>

    <section class="detail-section">
      <h4>操作</h4>
      <div class="action-row">
        <button
          v-if="model.row?.claimable"
          type="button"
          class="btn btn-primary btn-sm"
          data-testid="detail-claim"
          :disabled="busy"
          @click="emit('claim', model.row)"
        >认领</button>
        <button
          v-for="next in model.row?.allowedTransitions || []"
          :key="next.code"
          type="button"
          class="btn btn-sm"
          data-testid="detail-transition"
          :data-to="next.code"
          :disabled="busy"
          @click="emit('transition', { row: model.row, next })"
        >{{ next.actionLabel }}</button>
        <span v-if="!model.row?.claimable && (model.row?.allowedTransitions || []).length === 0" class="muted">
          已完成（终态），无后续流转。
        </span>
      </div>

      <div class="assign-row">
        <input
          v-model="assignOwner"
          type="text"
          data-testid="detail-assign-owner"
          placeholder="指派给：部门 / 姓名"
          :disabled="busy"
        />
        <button
          type="button"
          class="btn btn-sm"
          data-testid="detail-assign"
          :disabled="busy || !assignOwner.trim()"
          @click="submitAssign(model.row)"
        >指派</button>
      </div>
    </section>

    <section class="audit-section">
      <h4>流转留痕（{{ model.timelineCount }}）</h4>
      <p v-if="model.timeline.length === 0" class="muted">暂无操作记录。</p>
      <ul v-else class="audit-list">
        <li v-for="entry in model.timeline" :key="entry.id" data-testid="todo-audit-entry">
          <span class="audit-action">{{ entry.actionLabel }}</span>
          <span v-if="entry.changeText" class="strong" data-testid="todo-audit-change">{{ entry.changeText }}</span>
          <span class="muted" :title="entry.actor">操作人 {{ entry.actorName }}</span>
          <span class="muted" data-testid="todo-audit-at">{{ formatDateTimeLong(entry.at) }}</span>
        </li>
      </ul>
    </section>
  </aside>
</template>
