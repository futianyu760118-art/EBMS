<script setup>
// F8（PAND-86）纯展示组件：入参即 buildTodoModel 的结果，便于直接做 SSR 渲染断言。
// 七列 = 事项 / 来源 / 关联结果或原因 / 责任人 / 截止时间 / 状态 / 操作。
defineProps({
  model: { type: Object, required: true },
});

const emit = defineEmits(['open', 'claim', 'transition']);

function onTransition(row, next) {
  emit('transition', { row, next });
}
</script>

<template>
  <div>
    <ul class="stat-strip">
      <li v-for="stat in model.stats" :key="stat.key" :data-testid="`todo-stat-${stat.key}`">
        <span class="stat-value">{{ stat.value }}</span>
        <span class="stat-label muted">{{ stat.label }}</span>
      </li>
    </ul>

    <p class="alert alert-info" data-testid="todo-source-notice">{{ model.sourceNotice }}</p>
    <p v-if="model.triggerNotice" class="alert alert-ok" data-testid="todo-trigger-notice">
      {{ model.triggerNotice }}
    </p>
    <p v-if="model.triggerMissingCount > 0" class="alert alert-error" data-testid="todo-trigger-missing">
      有 {{ model.triggerMissingCount }} 条自动产生的待办缺少触发依据——自动产生的待办必须可回溯到关联结果或原因。
    </p>
    <p v-if="model.overdueNotice" class="alert alert-warning" data-testid="todo-overdue-notice">
      {{ model.overdueNotice }}
    </p>
    <p class="muted" data-testid="todo-ownership-notice">{{ model.ownershipNotice }}</p>

    <p v-if="model.filtered" class="muted" data-testid="todo-filtered-hint">
      已按筛选条件过滤，命中 {{ model.filteredCount }} 条；上方计数为全部待办。
    </p>

    <table class="data-table todo-table">
      <caption class="muted">每条待办含：事项、来源、关联结果或原因、责任人、截止时间、状态</caption>
      <thead>
        <tr>
          <th>事项</th>
          <th>来源</th>
          <th>关联结果 / 原因</th>
          <th>责任人</th>
          <th>截止时间</th>
          <th>状态</th>
          <th class="col-actions">操作</th>
        </tr>
      </thead>
      <tbody>
        <tr
          v-for="row in model.rows"
          :key="row.id"
          data-testid="todo-row"
          :data-code="row.code"
          :data-status="row.status"
          :class="{ 'row-overdue': row.overdue, 'row-done': row.status === 'done' }"
        >
          <td>
            <button type="button" class="link-title" data-testid="todo-title" @click="emit('open', row)">
              {{ row.title }}
            </button>
            <div class="muted">{{ row.code }}</div>
            <span v-if="row.overdue" class="badge badge-danger" data-testid="todo-overdue" :title="row.overdueLabel">
              {{ row.overdueLabel }}
            </span>
          </td>
          <td data-testid="todo-source">
            <span class="badge" :class="row.autoGenerated ? 'badge-rule' : 'badge-manual'">
              {{ row.sourceLabel }}
            </span>
            <div v-if="row.autoGenerated" class="muted trigger-line" data-testid="todo-trigger">
              {{ row.triggerRule || '触发依据缺失' }}
            </div>
          </td>
          <td data-testid="todo-relation">
            <template v-if="row.hasRelation">
              <div v-for="ref in row.relatedRefs" :key="ref.refId" class="relation-line">
                <span class="tag">{{ ref.refTypeLabel }}</span>
                <span class="strong">{{ ref.label }}</span>
                <span v-if="ref.code" class="muted">{{ ref.code }}</span>
              </div>
            </template>
            <span v-else class="muted">{{ row.relationText }}</span>
          </td>
          <td data-testid="todo-owner">
            <span v-if="row.assigned" class="strong">{{ row.ownerLabel }}</span>
            <span v-else class="unassigned-mark" data-testid="todo-unassigned">未指派</span>
          </td>
          <td data-testid="todo-due" :class="{ 'warn-inline': row.overdue }">{{ row.dueText }}</td>
          <td data-testid="todo-status">
            <span class="badge" :class="`badge-status-${row.status}`">{{ row.statusLabel }}</span>
          </td>
          <td class="col-actions">
            <button
              v-if="row.claimable"
              type="button"
              class="btn btn-sm"
              data-testid="todo-claim"
              @click="emit('claim', row)"
            >认领</button>
            <button
              v-for="next in row.allowedTransitions"
              :key="next.code"
              type="button"
              class="btn btn-sm"
              data-testid="todo-transition"
              :data-to="next.code"
              @click="onTransition(row, next)"
            >{{ next.actionLabel }}</button>
            <span v-if="!row.claimable && row.allowedTransitions.length === 0" class="muted">—</span>
          </td>
        </tr>
        <tr v-if="model.rows.length === 0">
          <td colspan="7" class="muted" data-testid="todo-empty">没有符合筛选条件的待办事项。</td>
        </tr>
      </tbody>
    </table>
  </div>
</template>
