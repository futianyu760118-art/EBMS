//
// 口径以后端返回为准：状态/来源枚举、逾期标记、可流转动作、关联结果或原因的可读文案
// 全部由接口下发，前端不自行判定「是否逾期」、不自行维护枚举清单，
// 避免与后端的状态机、逾期比较口径（截止时间 vs 当前时间）漂移。

/** 责任人未指派时的文案（自动产生但尚未被认领）。 */
export const UNASSIGNED_LABEL = '未指派';

/** 截止时间缺失时的文案。 */
export const NO_DUE_LABEL = '无截止时间';

/** 关联结果或原因缺失时的文案。 */
export const NO_RELATION_LABEL = '未关联结果或原因';

/** 规则自动产生的待办的触发依据缺失时的兜底文案（边界：自动产生必带触发依据）。 */
export const NO_TRIGGER_LABEL = '未记录触发依据';

/** 状态 → 色调（仅影响样式，取值仍以后端 status 为准）。 */
const STATUS_TONE = { pending: 'warn', in_progress: 'info', done: 'ok' };

/** 状态流转的动作文案：把「待处理 → 处理中」翻译成界面上要点的按钮。 */
const TRANSITION_ACTION = {
  'pending->in_progress': '开始处理',
  'in_progress->done': '标记完成',
  'in_progress->pending': '退回待处理',
};

/**
 * 截止时间 → 列表列要显示的日历日（YYYY-MM-DD）。
 *
 * 口径：截止时间是业务上的「哪一天到期」，按本地日历渲染（与 format.js 的时间格式化同一约定）。
 * 不能直接切 ISO 字符串取前 10 位：接口返回的是 UTC 时刻，业务时区（UTC+8）的零点在 UTC 上是
 * 前一天 16:00，切字符串会把「9-30 到期」显示成「9-29」——截止时间与逾期标记都会失真。
 */
export function dueText(dueAt) {
  if (!dueAt) return NO_DUE_LABEL;
  const date = new Date(dueAt);
  if (Number.isNaN(date.getTime())) return String(dueAt).slice(0, 10);
  const pad = (n) => String(n).padStart(2, '0');
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
}

/**
 * 截止时间 → 详情里显示的本地日期时间（含时刻）。
 * 逾期以「截止时刻 vs 当前时刻」精确比较（AC 判定标准），详情写明时刻，避免
 * 列表只显示日期时出现「显示今天到期、却已判逾期」的观感矛盾。
 */
export function dueDateTimeText(dueAt) {
  if (!dueAt) return NO_DUE_LABEL;
  const date = new Date(dueAt);
  if (Number.isNaN(date.getTime())) return String(dueAt);
  const pad = (n) => String(n).padStart(2, '0');
  return (
    `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ` +
    `${pad(date.getHours())}:${pad(date.getMinutes())}`
  );
}

export function triggerRuleText(basis) {
  if (!basis) return null;
  const code = basis.ruleCode || '';
  const label = basis.ruleLabel || '';
  if (code && label) return `${code} · ${label}`;
  return code || label || null;
}

/**
 * 触发依据锚定的结论/原因（边界：自动产生的 TODO 必须可回溯到关联结果或原因）。
 * 后端在触发依据里同时给出 id 与可读编码，前端只用可读部分。
 */
export function triggerAnchorText(basis) {
  if (!basis) return null;
  if (basis.resultMetricCode) return `结果指标 ${basis.resultMetricCode}`;
  if (basis.reasonId) return '原因项';
  return null;
}

/** 单条待办 → 列表行模型（AC 场景 1 的七列 + 场景 3/4 的状态与逾期标记）。 */
export function buildTodoRow(item) {
  const relatedRefs = Array.isArray(item.relatedRefs) ? item.relatedRefs : [];
  const allowed = Array.isArray(item.allowedTransitions) ? item.allowedTransitions : [];

  return {
    id: item.id,
    code: item.code,
    // 1. 事项
    title: item.title,
    // 2. 来源（规则自动产生 / 人工派发）
    source: item.source,
    sourceLabel: item.sourceLabel || item.source,
    autoGenerated: Boolean(item.autoGenerated),
    // 3. 关联结果或原因（后端已解析出可读 label）
    relatedRefs: relatedRefs.map((ref) => ({
      refType: ref.refType,
      refTypeLabel: ref.refTypeLabel || ref.refType,
      refId: ref.refId,
      code: ref.code ?? null,
      label: ref.label,
    })),
    relationText: item.relationText || NO_RELATION_LABEL,
    hasRelation: relatedRefs.length > 0,
    // 4. 责任人
    owner: item.owner ?? null,
    ownerLabel: item.ownerLabel || UNASSIGNED_LABEL,
    assigned: Boolean(item.assigned),
    // 可认领 = 未指派且未完成（已完成的不能再被认领，与后端一致）
    claimable: !item.assigned && item.status !== 'done',
    // 5. 截止时间
    dueAt: item.dueAt ?? null,
    dueText: dueText(item.dueAt),
    dueDateTimeText: dueDateTimeText(item.dueAt),
    // 6. 状态
    status: item.status,
    statusLabel: item.statusLabel || item.status,
    statusTone: STATUS_TONE[item.status] || 'muted',
    // 逾期标记（场景 4：逾期项有区分标记）——判定完全取自后端
    overdue: Boolean(item.overdue),
    overdueLabel: item.overdueLabel ?? null,
    overdueTone: item.overdueTone ?? null,
    // 7. 可执行动作（只渲染状态机允许的边，避免出现注定被拒的按钮）
    allowedTransitions: allowed.map((next) => ({
      code: next.code,
      label: next.label,
      actionLabel: TRANSITION_ACTION[`${item.status}->${next.code}`] || `转为${next.label}`,
    })),
    // 边界：自动产生的待办必须记录触发依据（关联结果 / 原因 / 规则）
    triggerBasis: item.triggerBasis ?? null,
    triggerSummary: item.triggerBasis?.summary ?? null,
    triggerRule: triggerRuleText(item.triggerBasis),
    triggerAnchor: triggerAnchorText(item.triggerBasis),
    triggerMissing: item.source === 'rule' && !item.triggerBasis,
    ruleKey: item.ruleKey ?? null,
    // 四视图落点：TODO 对象详情页（F11 已支持的 hash 路由）
    href: `#/todo/${item.id}`,
  };
}

/** 后端 GET /todos 载荷 → 列表渲染模型。 */
export function buildTodoModel(payload) {
  const items = payload?.items ?? [];
  const summary = payload?.summary ?? {};
  const rows = items.map(buildTodoRow);

  const total = Number(summary.total ?? rows.length);
  const ruleSourced = Number(summary.ruleSourced ?? rows.filter((r) => r.autoGenerated).length);
  const manualSourced = Number(summary.manualSourced ?? rows.filter((r) => !r.autoGenerated).length);
  const overdueCount = Number(summary.overdue ?? rows.filter((r) => r.overdue).length);
  const unassignedCount = rows.filter((r) => !r.assigned && r.status !== 'done').length;
  // 来源非空但触发依据缺失的自动待办数（边界自检：应当恒为 0）
  const triggerMissingCount = rows.filter((r) => r.triggerMissing).length;

  return {
    now: payload?.now ?? null,
    // 筛选器的取值来源：状态与来源枚举由后端下发，前端不硬编码
    statuses: payload?.statuses ?? [],
    sources: payload?.sources ?? [],
    filters: payload?.filters ?? {},
    filteredCount: rows.length,
    filtered: Boolean(
      payload?.filters &&
        Object.values(payload.filters).some((v) => v !== null && v !== undefined && v !== '')
    ),
    stats: [
      { key: 'total', label: '待办总数', value: total },
      { key: 'pending', label: '待处理', value: Number(summary.pending ?? 0) },
      { key: 'in_progress', label: '处理中', value: Number(summary.inProgress ?? 0) },
      { key: 'done', label: '已完成', value: Number(summary.done ?? 0) },
      { key: 'overdue', label: '已逾期', value: overdueCount },
      { key: 'unassigned', label: '待认领', value: unassignedCount },
    ],
    // 场景 2 判定：两种来源并存，且在界面上可见
    bothSourcesPresent: Boolean(summary.bothSourcesPresent),
    sourceNotice:
      `两种来源并存：规则自动产生 ${ruleSourced} 条 / 人工派发 ${manualSourced} 条` +
      (summary.bothSourcesPresent ? '（并存成立）' : '（当前仅一种来源）'),
    // 边界自述：自动产生的待办必须含触发依据
    triggerNotice:
      ruleSourced === 0
        ? null
        : triggerMissingCount === 0
          ? `规则自动产生的 ${ruleSourced} 条待办均含触发依据（规则 + 关联结果或原因）`
          : `有 ${triggerMissingCount} 条自动产生的待办缺少触发依据`,
    triggerMissingCount,
    overdueNotice:
      overdueCount === 0
        ? null
        : `有 ${overdueCount} 条已过截止时间且未完成（逾期判定 = 截止时间早于当前时间）`,
    // 口径自述：责任如何落到人
    ownershipNotice: '状态流转口径：待处理 →（开始处理）→ 处理中 →（标记完成）→ 已完成；已完成不可回流。',
    rows,
  };
}

/** 留痕条目 → 时间线模型（AC 场景 3：流转留痕含操作人、时间）。 */
function buildTimelineEntry(entry, statusLabelOf) {
  const before = entry.before || {};
  const after = entry.after || {};
  let changeText = null;

  if (entry.action === 'todo.claim' || entry.action === 'todo.assign') {
    changeText = `责任人：${before.owner || UNASSIGNED_LABEL} → ${after.owner || UNASSIGNED_LABEL}`;
  } else if (entry.action === 'todo.transition') {
    changeText = `状态：${statusLabelOf(before.status)} → ${statusLabelOf(after.status)}`;
  } else if (entry.action === 'todo.rule_generate') {
    changeText = '由规则自动产生';
  } else if (entry.action === 'todo.create') {
    changeText = `人工派发给 ${after.owner || UNASSIGNED_LABEL}`;
  }

  return {
    id: entry.id,
    action: entry.action,
    // 可读动作名以后端下发为准（后端是留痕动作枚举的唯一出处）
    actionLabel: entry.actionLabel || entry.action,
    actor: entry.actor,
    actorName: entry.actorName || entry.actor,
    at: entry.at,
    changeText,
    before,
    after,
  };
}

/** 后端 GET /todos/:id 载荷 → 详情渲染模型。 */
export function buildTodoDetailModel(detail) {
  const statuses = detail?.statuses ?? [];
  const statusLabelOf = (code) => statuses.find((s) => s.code === code)?.label || code || '—';

  const row = detail?.todo ? buildTodoRow(detail.todo) : null;

  return {
    row,
    statuses,
    sources: detail?.sources ?? [],
    timeline: (detail?.audit ?? []).map((entry) => buildTimelineEntry(entry, statusLabelOf)),
    timelineCount: Number(detail?.auditCount ?? (detail?.audit ?? []).length),
    // 边界：自动产生的待办在详情里显式展开触发依据，供责任人核对「为什么派给我」
    trigger: row?.autoGenerated
      ? {
          rule: row.triggerRule || NO_TRIGGER_LABEL,
          summary: row.triggerSummary || NO_TRIGGER_LABEL,
          anchor: row.triggerAnchor,
          detectedAt: row.triggerBasis?.detectedAt ?? null,
          period:
            row.triggerBasis?.periodType && row.triggerBasis?.periodValue
              ? `${row.triggerBasis.periodType}/${row.triggerBasis.periodValue}`
              : null,
        }
      : null,
  };
}

/**
 * 日期筛选值（YYYY-MM-DD，来自 <input type="date">）按本地「当天结束」解释。
 * 使「截止时间不晚于 9-30」包含 9-30 全天，而不是把 9-30 白天到期的项判为超出。
 */
export function endOfLocalDay(dateText) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(dateText ?? ''));
  if (!match) return dateText;
  const date = new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3]), 23, 59, 59, 999);
  return date.toISOString();
}

/** 筛选条件 → 查询串（空值不下发，避免后端把空字符串当成筛选值）。 */
export function todoQuery(filters = {}) {
  const params = new URLSearchParams();
  if (filters.owner) params.set('owner', filters.owner);
  if (filters.status) params.set('status', filters.status);
  if (filters.source) params.set('source', filters.source);
  if (filters.dueBefore) params.set('due_before', endOfLocalDay(filters.dueBefore));
  if (filters.overdue === true) params.set('overdue', 'true');
  if (filters.overdue === false) params.set('overdue', 'false');
  const query = params.toString();
  return query ? `?${query}` : '';
}
