test('场景 4 / 判定标准：逾期由截止时间与当前时间比较得出，逾期项有区分标记', async () => {
  const data = await list();
  const unclaimed = byId(data.items, IDS.todos.ruleUnclaimed);
  const doneItem = byId(data.items, IDS.todos.done);

  // 逾期项：截止时间（2026-09-20）早于当前时间，且未完成
  assert.equal(unclaimed.overdue, true, '截止时间早于当前时间且未完成的项应判逾期');
  assert.ok(unclaimed.overdueLabel, '逾期项带可读的区分标记');
  assert.equal(unclaimed.overdueTone, 'danger');

  // 逾期标记与「截止时间 vs 当前时间」这一判定同源
  const now = new Date();
  assert.equal(
    unclaimed.overdue,
    isOverdue({ dueAt: unclaimed.dueAt, status: unclaimed.status }, now)
  );
  assert.ok(new Date(unclaimed.dueAt).getTime() < now.getTime(), '逾期项的截止时间确实已过');

  // 已完成项即使截止时间已过也不判逾期（终态离开逾期统计口径）
  assert.ok(new Date(doneItem.dueAt).getTime() < now.getTime(), '夹具的已完成项截止时间已过');
  assert.equal(doneItem.overdue, false);
  assert.equal(doneItem.overdueLabel, null);

  // 逾期专项筛选：只回逾期项，且数量与汇总一致
  const overdueOnly = await list('?overdue=true');
  assert.ok(overdueOnly.items.length > 0);
  assert.ok(overdueOnly.items.every((t) => t.overdue === true));
  assert.equal(overdueOnly.summary.overdue, overdueOnly.items.length);

  const notOverdue = await list('?overdue=false');
  assert.ok(notOverdue.items.every((t) => t.overdue === false));

  // 领域层纯函数：无截止时间 / 已完成 / 非法时间 均不判逾期
  assert.equal(isOverdue({ dueAt: null, status: 'pending' }), false);
  assert.equal(isOverdue({ dueAt: '2020-01-01T00:00:00Z', status: 'done' }), false);
  assert.equal(isOverdue({ dueAt: 'not-a-date', status: 'pending' }), false);
  assert.equal(overdueBadge({ dueAt: '2020-01-01T00:00:00Z', status: 'done' }).overdue, false);
});

