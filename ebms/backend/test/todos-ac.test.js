test('一致性：规则产生的待办，其触发依据与 F1 指标集的口径逐字一致', async () => {
  const dry = await api('/todos/rule-scan?dry_run=1', { method: 'POST', auth: true, body: { periodType: SEED_PERIOD.periodType, periodValue: SEED_PERIOD.periodValue } });
  const metrics = await api(`/results?period_type=${SEED_PERIOD.periodType}&period_value=${SEED_PERIOD.periodValue}`);
  const exceeded = metrics.json.data.items.filter((m) => m.deviation && m.deviation.exceeded === true);
  assert.ok(exceeded.length > 0, '夹具应包含超阈值指标');

  const deviationCandidates = dry.json.data.candidates.filter((c) => c.ruleCode === 'R-RESULT-DEVIATION');
  assert.deepEqual(
    deviationCandidates.map((c) => c.refId).sort(),
    exceeded.map((m) => m.id).sort(),
    '触发集合应与「已供给且超阈值」的指标集合完全一致'
  );
  for (const candidate of deviationCandidates) {
    const metric = exceeded.find((m) => m.id === candidate.refId);
    assert.equal(candidate.triggerBasis.resultMetricCode, metric.code);
    assert.ok(candidate.triggerBasis.summary.includes(`超过阈值 ${metric.deviation.thresholdPct}%`));
    // 截止时间 = 该指标数据截止时间 + 规则天数（可复现，不依赖扫描时刻）
    const expected = new Date(new Date(metric.dataCutoffAt).getTime() + RULES['R-RESULT-DEVIATION'].dueDays * 86400000).toISOString();
    assert.equal(candidate.dueAt, expected);
  }
});

