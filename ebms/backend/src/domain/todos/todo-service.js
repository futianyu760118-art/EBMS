// F8（PAND-86）TODO 用例层：列表 / 详情 / 人工派发 / 认领 / 指派 / 状态流转。
// 规则自动产生走 todo-rule-engine（同一套写入与留痕口径）。
//
// 留痕口径（AC 判定标准）：认领、指派、状态流转各自写一条 audit_log，
// 记录操作人、时间与 before/after —— 写入与留痕在同一事务内提交。

const crypto = require('crypto');
const { withTransaction } = require('../../db/pool');
const { badRequest, notFound, conflict } = require('../../http/errors');
const auditRepo = require('../audit/audit-repository');
const resultRepo = require('../results/result-repository');
const reasonRepo = require('../reason/reason-repository');
const todoRepo = require('./todo-repository');
const {
  DEFAULT_STATUS,
  TODO_SOURCES,
  TODO_SOURCE_CODES,
  isValidStatus,
  isValidSource,
  statusLabel,
  sourceLabel,
  listStatuses,
  listSources,
  allowedTransitions,
  canTransition,
  isOverdue,
  overdueBadge,
} = require('./todo-status');

// 「关联结果或原因」的两类引用。字段与取值口径在此固定，前端只提交 refId。
const UUID_PATTERN = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;

const RELATED_REF_TYPES = Object.freeze({
  result: Object.freeze({ code: 'result', label: '结果指标' }),
  reason: Object.freeze({ code: 'reason', label: '原因项' }),
});

function actorNameOf(actor) {
  return actor.displayName || actor.username || actor.id;
}

function toIso(value) {
  if (!value) return null;
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
}

// ---------------------------------------------------------------- 序列化

/**
 * 场景 1 的七列：事项 / 来源 / 关联结果或原因 / 责任人 / 截止时间 / 状态（+ 操作）。
 * 逾期标记与状态流转动作随行下发，前端不自行推导。
 */
function serializeTodo(row, { now = new Date() } = {}) {
  const relatedRefs = Array.isArray(row.related_refs) ? row.related_refs : [];
  const badge = overdueBadge({ dueAt: row.due_at, status: row.status }, now);

  return {
    id: row.id,
    code: row.code,
    title: row.title,
    // 来源：两类并存（规则自动产生 / 人工派发）
    source: row.source,
    sourceLabel: sourceLabel(row.source),
    autoGenerated: row.source === 'rule',
    // 关联结果或原因（服务端回源解析出的 label，非前端提交值）
    relatedRefs,
    relationText: relatedRefs.length > 0
      ? relatedRefs.map((r) => r.label).join('、')
      : '未关联结果或原因',
    // 责任人：自动产生但尚未被认领时为「未指派」
    owner: row.owner || null,
    ownerLabel: row.owner || '未指派',
    assigned: Boolean(row.owner),
    dueAt: toIso(row.due_at),
    dueState: overdueBadge({ dueAt: row.due_at, status: row.status }, now),
    overdue: badge.overdue,
    overdueLabel: badge.label,
    overdueTone: badge.tone,
    // 状态：待处理 / 处理中 / 已完成
    status: row.status,
    statusLabel: statusLabel(row.status),
    allowedTransitions: allowedTransitions(row.status),
    // 自动产生的待办必须可回溯其触发依据（关联结果 / 原因 / 规则）
    triggerBasis: row.trigger_basis || null,
    ruleKey: row.rule_key || null,
    createdBy: row.created_by,
    createdAt: toIso(row.created_at),
    updatedAt: toIso(row.updated_at),
  };
}

function serializeAudit(row) {
  return {
    id: String(row.id),
    action: row.action,
    actionLabel: AUDIT_ACTION_LABELS[row.action] || row.action,
    actor: row.actor,
    actorName: row.actor_name,
    before: row.before,
    after: row.after,
    at: toIso(row.at),
  };
}

const AUDIT_ACTION_LABELS = Object.freeze({
  'todo.create': '人工派发',
  'todo.rule_generate': '规则自动产生',
  'todo.claim': '认领',
  'todo.assign': '指派',
  'todo.transition': '状态流转',
});

// ---------------------------------------------------------------- 读

/** 场景 1~4：列表（含筛选、逾期标记与汇总）。 */
async function listTodos({ owner, status, source, dueBefore, overdue, limit } = {}) {
  const now = new Date();
  const fields = {};
  if (status !== undefined && status !== null && status !== '' && !isValidStatus(status)) {
    fields.status = `状态只能是 ${listStatuses().map((s) => s.code).join(' / ')}`;
  }
  if (source !== undefined && source !== null && source !== '' && !isValidSource(source)) {
    fields.source = `来源只能是 ${TODO_SOURCE_CODES.join(' / ')}`;
  }
  if (Object.keys(fields).length > 0) {
    throw badRequest('TODO_FILTER_INVALID', '筛选条件不合法', { fields });
  }

  const dueBeforeIso = toIso(dueBefore);
  if (dueBefore && !dueBeforeIso) {
    throw badRequest('TODO_DUE_BEFORE_INVALID', '截止时间筛选值不是合法的日期时间', {
      fields: { dueBefore: '请使用 ISO 8601 日期时间' },
    });
  }

  const rows = await todoRepo.list({
    owner: owner || null,
    status: status || null,
    source: source || null,
    dueBefore: dueBeforeIso,
    overdue: parseOverdueFlag(overdue),
    limit,
    now,
  });

  const items = rows.map((row) => serializeTodo(row, { now }));
  const summary = await todoRepo.summary({ now });

  return {
    now: now.toISOString(),
    // 筛选器取值来源：状态与来源枚举由后端下发，前端不硬编码
    statuses: listStatuses(),
    sources: listSources(),
    filters: {
      owner: owner || null,
      status: status || null,
      source: source || null,
      dueBefore: dueBeforeIso,
      overdue: parseOverdueFlag(overdue),
    },
    summary: {
      total: summary.total,
      pending: summary.pending,
      inProgress: summary.in_progress,
      done: summary.done,
      ruleSourced: summary.rule_sourced,
      manualSourced: summary.manual_sourced,
      overdue: summary.overdue,
      // 场景 2 判定：两种来源并存
      bothSourcesPresent: summary.rule_sourced > 0 && summary.manual_sourced > 0,
    },
    total: items.length,
    items,
  };
}

/** 详情：七列字段 + 留痕时间线（谁在何时把什么改成了什么）。 */
async function getTodoDetail(id) {
  const row = await todoRepo.findById(id);
  if (!row) throw notFound('TODO_NOT_FOUND', `待办事项不存在：${id}`);

  const now = new Date();
  const audits = await auditRepo.listByEntity('todo', String(row.id));

  return {
    now: now.toISOString(),
    // 状态与来源枚举随详情下发，使留痕里的 before/after 状态码在页面上有可读文案
    statuses: listStatuses(),
    sources: listSources(),
    todo: serializeTodo(row, { now }),
    audit: audits.map(serializeAudit),
    auditCount: audits.length,
  };
}

function parseOverdueFlag(value) {
  if (value === undefined || value === null || value === '') return null;
  if (value === true || value === 'true') return true;
  if (value === false || value === 'false') return false;
  throw badRequest('TODO_OVERDUE_FLAG_INVALID', 'overdue 只能是 true / false');
}

// ---------------------------------------------------------------- 关联结果或原因（服务端回源）

/**
 * related_refs 的 label 一律服务端回源解析：前端只提交 { refType, refId }，
 * 不提交 label，避免展示文案被伪造或指向不存在的结论/原因。
 */
async function resolveRelatedRefs(inputs) {
  if (inputs === undefined || inputs === null) return { refs: [] };
  if (!Array.isArray(inputs)) {
    throw badRequest('TODO_RELATED_REFS_INVALID', 'relatedRefs 必须是数组', {
      fields: { relatedRefs: '应为 [{ refType, refId }] 数组' },
    });
  }

  const refs = [];
  const seen = new Set();
  for (const [index, raw] of inputs.entries()) {
    const refType = typeof raw?.refType === 'string' ? raw.refType.trim() : '';
    const refId = typeof raw?.refId === 'string' ? raw.refId.trim() : '';
    const fieldPath = `relatedRefs[${index}]`;

    if (!Object.prototype.hasOwnProperty.call(RELATED_REF_TYPES, refType)) {
      throw badRequest('TODO_RELATED_REF_TYPE_INVALID', `非法的关联类型：${refType || '（空）'}`, {
        fields: { [fieldPath]: `refType 只能是 ${Object.keys(RELATED_REF_TYPES).join(' / ')}` },
      });
    }
    if (!refId) {
      throw badRequest('TODO_RELATED_REF_ID_REQUIRED', '关联对象标识不能为空', {
        fields: { [fieldPath]: 'refId 不能为空' },
      });
    }

    const key = `${refType}:${refId}`;
    if (seen.has(key)) continue;
    seen.add(key);

    // 非 UUID 形状的入参直接判为「不存在」，不让 22P02 变成 500
    if (!UUID_PATTERN.test(refId)) {
      throw notFound(
        refType === 'result' ? 'TODO_RELATED_RESULT_NOT_FOUND' : 'TODO_RELATED_REASON_NOT_FOUND',
        `关联的${RELATED_REF_TYPES[refType].label}不存在：${refId}`
      );
    }

    if (refType === 'result') {
      const metric = await resultRepo.findById(refId);
      if (!metric) {
        throw notFound('TODO_RELATED_RESULT_NOT_FOUND', `关联的结果指标不存在：${refId}`);
      }
      refs.push({
        refType,
        refTypeLabel: RELATED_REF_TYPES.result.label,
        refId: metric.id,
        code: metric.code,
        label: metric.name,
      });
    } else {
      const reason = await reasonRepo.findById(refId);
      if (!reason) {
        throw notFound('TODO_RELATED_REASON_NOT_FOUND', `关联的原因项不存在：${refId}`);
      }
      refs.push({
        refType,
        refTypeLabel: RELATED_REF_TYPES.reason.label,
        refId: reason.id,
        code: null,
        label: reason.name,
        direction: reason.direction,
      });
    }
  }
  return { refs };
}

// ---------------------------------------------------------------- 写

function generateCode(now = new Date()) {
  const ymd = now.toISOString().slice(0, 10).replace(/-/g, '');
  return `TODO-${ymd}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
}

/**
 * 人工派发（场景 2 的来源之一）。
 * 接口只接受 source='manual'：自动产生的待办只能由规则引擎写入，
 * 否则「自动产生必须带触发依据」这条边界可以被外部调用绕过。
 */
async function createTodo(actor, input = {}) {
  const fields = {};
  const title = typeof input.title === 'string' ? input.title.trim() : '';
  if (!title) fields.title = '事项标题不能为空';

  const owner = typeof input.owner === 'string' ? input.owner.trim() : '';
  if (!owner) fields.owner = '人工派发必须指定责任人';

  const dueAt = input.dueAt === undefined || input.dueAt === null || input.dueAt === ''
    ? null
    : toIso(input.dueAt);
  if (input.dueAt && !dueAt) fields.dueAt = '截止时间不是合法的日期时间';

  if (input.source !== undefined && input.source !== 'manual') {
    fields.source = '人工派发的来源固定为 manual；规则自动产生由规则引擎写入';
  }

  // 先做字段级校验，再回源解析关联（避免半截请求触发多余的库查询）
  if (Object.keys(fields).length > 0) {
    throw badRequest('TODO_CREATE_INVALID', '新增待办入参不合法', { fields });
  }

  const { refs } = await resolveRelatedRefs(input.relatedRefs);

  const created = await withTransaction(async (client) => {
    const row = await insertWithCodeRetry(client, {
      title,
      source: 'manual',
      status: DEFAULT_STATUS,
      owner,
      dueAt,
      relatedRefs: refs,
      triggerBasis: null,
      ruleKey: null,
      createdBy: actor.id,
    });

    const audit = await auditRepo.record(client, {
      actor: actor.id,
      actorName: actorNameOf(actor),
      action: 'todo.create',
      entityType: 'todo',
      entityId: String(row.id),
      after: {
        code: row.code,
        title: row.title,
        source: row.source,
        owner: row.owner,
        dueAt: toIso(row.due_at),
        relatedRefs: refs,
      },
    });
    return { row, audit };
  });

  return {
    changed: true,
    todo: serializeTodo(created.row),
    audit: serializeAudit(created.audit),
  };
}

/** code 有唯一约束：极小概率撞码时重试，避免把「随机撞码」当成业务失败。 */
async function insertWithCodeRetry(client, payload) {
  let lastError = null;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      return await todoRepo.insert(client, { ...payload, code: generateCode() });
    } catch (err) {
      if (err.code !== '23505' || !String(err.constraint || '').includes('code')) throw err;
      lastError = err;
    }
  }
  throw conflict('TODO_CODE_CONFLICT', `待办编号生成冲突：${lastError?.detail || ''}`);
}

/** 认领：把责任人认到自己名下。仅未指派或本人已认领时可执行（幂等）。 */
async function claimTodo(actor, id) {
  const existing = await todoRepo.findById(id);
  if (!existing) throw notFound('TODO_NOT_FOUND', `待办事项不存在：${id}`);

  const actorName = actorNameOf(actor);
  if (existing.status === 'done') {
    throw conflict('TODO_ALREADY_DONE', '已完成的待办不能再被认领');
  }
  if (existing.owner && existing.owner !== actorName) {
    throw conflict('TODO_ALREADY_CLAIMED', `该待办已有责任人：${existing.owner}`);
  }
  if (existing.owner === actorName) {
    return { changed: false, alreadyOwned: true, todo: serializeTodo(existing), audit: null };
  }

  const now = new Date();
  const result = await withTransaction(async (client) => {
    const row = await todoRepo.updateOwner(client, id, actorName, now);
    const audit = await auditRepo.record(client, {
      actor: actor.id,
      actorName,
      action: 'todo.claim',
      entityType: 'todo',
      entityId: String(row.id),
      before: { owner: null },
      after: { owner: row.owner },
    });
    return { row, audit };
  });

  return { changed: true, alreadyOwned: false, todo: serializeTodo(result.row), audit: serializeAudit(result.audit) };
}

/** 指派：管理责任人 / 决策者把待办交给某个责任人（幂等，同人不再留痕）。 */
async function assignTodo(actor, id, { owner } = {}) {
  const existing = await todoRepo.findById(id);
  if (!existing) throw notFound('TODO_NOT_FOUND', `待办事项不存在：${id}`);

  const nextOwner = typeof owner === 'string' ? owner.trim() : '';
  if (!nextOwner) {
    throw badRequest('TODO_ASSIGN_OWNER_REQUIRED', '指派必须指定责任人', {
      fields: { owner: '责任人不能为空' },
    });
  }
  if (existing.owner === nextOwner) {
    return { changed: false, unchangedOwner: true, todo: serializeTodo(existing), audit: null };
  }

  const now = new Date();
  const result = await withTransaction(async (client) => {
    const row = await todoRepo.updateOwner(client, id, nextOwner, now);
    const audit = await auditRepo.record(client, {
      actor: actor.id,
      actorName: actorNameOf(actor),
      action: 'todo.assign',
      entityType: 'todo',
      entityId: String(row.id),
      before: { owner: existing.owner || null },
      after: { owner: row.owner },
    });
    return { row, audit };
  });

  return { changed: true, unchangedOwner: false, todo: serializeTodo(result.row), audit: serializeAudit(result.audit) };
}

/** 状态流转：只接受状态机允许的边，非法流转（含终态回流）一律拒绝并提示合法目标。 */
async function transitionTodo(actor, id, { status } = {}) {
  const existing = await todoRepo.findById(id);
  if (!existing) throw notFound('TODO_NOT_FOUND', `待办事项不存在：${id}`);

  if (!isValidStatus(status)) {
    throw badRequest('TODO_STATUS_INVALID', `非法的目标状态：${status || '（空）'}`, {
      fields: { status: `状态只能是 ${listStatuses().map((s) => s.code).join(' / ')}` },
    });
  }
  if (!canTransition(existing.status, status)) {
    throw badRequest('TODO_TRANSITION_INVALID', `不允许从「${statusLabel(existing.status)}」流转到「${statusLabel(status)}」`, {
      fields: { status: `${statusLabel(existing.status)} 可流转到：${allowedTransitions(existing.status).map((s) => s.label).join('、') || '（终态，无后续流转）'}` },
      from: existing.status,
      to: status,
      allowed: allowedTransitions(existing.status).map((s) => s.code),
    });
  }

  const now = new Date();
  const result = await withTransaction(async (client) => {
    const row = await todoRepo.updateStatus(client, id, status, now);
    const audit = await auditRepo.record(client, {
      actor: actor.id,
      actorName: actorNameOf(actor),
      action: 'todo.transition',
      entityType: 'todo',
      entityId: String(row.id),
      before: { status: existing.status },
      after: { status: row.status },
    });
    return { row, audit };
  });

  return { changed: true, todo: serializeTodo(result.row), audit: serializeAudit(result.audit) };
}

